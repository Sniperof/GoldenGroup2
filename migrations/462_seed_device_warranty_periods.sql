-- تثبيت سياسة الكفالة القائمة فعلاً في كتالوج الأجهزة (DEF-042).
--
-- كانت مدد كفالة العقد (6/12/24/36) أرقاماً ثابتة داخل مكوّن الواجهة، لا جدول
-- لها ولا شاشة إدارة. وبعد ربط كفالة العقد بكتالوج الموديل صار 57 موديلاً من
-- أصل 58 عاجزاً عن منح أي كفالة، لأنه لا يملك بنداً واحداً معرّفاً.
--
-- والسياسة الواقعية مقروءة من البيانات نفسها لا من تخمين: من 25,173 جهازاً
-- مركّباً يحمل كفالة، هناك 25,158 جهازاً بكفالة 6 أشهر وزيارة واحدة بالضبط.
-- فهذه الهجرة تكتب ذلك البند على كل موديل لا يملك تعريفاً، أي تحوّل السياسة
-- المخفية إلى بيانات مُدارة قابلة للتعديل من «إدارة الأجهزة».
--
-- الموديلات التي عُرّفت كفالاتها يدوياً لا تُمسّ.
-- ============================================================

UPDATE public.device_models
   SET warranty_periods = '[{"label":"6 أشهر","months":6,"visits":1}]'::jsonb
 WHERE jsonb_array_length(COALESCE(warranty_periods, '[]'::jsonb)) = 0;

COMMIT;
