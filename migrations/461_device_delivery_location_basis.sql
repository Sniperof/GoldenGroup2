BEGIN;

-- ============================================================
-- 460_device_delivery_location_basis.sql
-- ============================================================
-- مهمة تسليم الجهاز كانت مُوطَّنة على عنوان الزبون (`client`)، فتُحسب منطقتها
-- من `clients.neighborhood` بدل عنوان التركيب. والتسليم بطبيعته يذهب إلى حيث
-- سيُركَّب الجهاز لا إلى حيث سُجّل الزبون، والعنوانان يختلفان فعلاً: 15 من 18
-- مهمة تسليم مفتوحة كانت مُنسَّبة لمنطقة غير منطقة جهازها.
--
-- الأثر أن المهمة تختفي من تخطيط الفريق المكلَّف بمنطقة التركيب بلا أي رسالة:
-- المنطقة في قائمة الفريق، وعنوان الجهاز مطابق لها، لكن المهمة تُقارَن بمنطقة
-- الزبون فلا تلتقي بشيء.
--
-- والدستور ينصّ على هذا بالاسم (open-tasks.md §BR-1): «موقع الجهاز (device):
-- للمهام التشغيلية المادية والتركيبية … مثل تسليم الجهاز device_delivery».
-- وكذلك planning.md §PL-R013. فالقيمة المخزَّنة كانت مخالفة للدستور لا تطبيقاً
-- لقرار مغاير.
--
-- ملاحظة: الكود يعامل 'contract' و'device' معاملة واحدة في كل المواضع
-- (`location_basis IN ('contract','device')`)، وكلاهما يقرأ
-- installed_devices.installation_geo_unit_id. اخترنا 'device' لموافقة نصّ
-- الدستور حرفياً.
-- ============================================================

UPDATE public.task_type_config
   SET location_basis = 'device'
 WHERE task_type = 'device_delivery'
   AND location_basis = 'client';

COMMIT;
