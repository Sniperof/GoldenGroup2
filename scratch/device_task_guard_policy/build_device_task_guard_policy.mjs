function styleSheet(sheet, usedRange, headerRange) {
  sheet.showGridLines = false;
  sheet.freezePanes.freezeRows(1);
  sheet.getRange(usedRange).format = {
    font: { name: "Aptos", size: 10, color: colors.text },
    wrapText: true,
    verticalAlignment: "top",
    horizontalAlignment: "right",
  };
  sheet.getRange(headerRange).format = {
    fill: colors.navy,
    font: { bold: true, color: "#FFFFFF", name: "Aptos", size: 10 },
    wrapText: true,
    horizontalAlignment: "center",
    verticalAlignment: "middle",
  };
  sheet.getRange(usedRange).format.borders = { preset: "outside", style: "thin", color: colors.border };
}

function setWidths(sheet, widths) {
  widths.forEach((width, index) => {
    sheet.getRangeByIndexes(0, index, 1, 1).format.columnWidth = width;
  });
}

function addTitle(sheet, title, subtitle, lastCol) {
  const titleRange = sheet.getRange(`A1:${lastCol}1`);
  titleRange.merge();
  titleRange.values = [[title]];
  titleRange.format = {
    fill: colors.navy,
    font: { bold: true, color: "#FFFFFF", size: 14, name: "Aptos" },
    horizontalAlignment: "right",
    verticalAlignment: "middle",
  };
  titleRange.format.rowHeight = 30;
  const subRange = sheet.getRange(`A2:${lastCol}2`);
  subRange.merge();
  subRange.values = [[subtitle]];
  subRange.format = {
    fill: colors.blue,
    font: { color: colors.text, size: 10, name: "Aptos" },
    horizontalAlignment: "right",
    verticalAlignment: "middle",
    wrapText: true,
  };
  subRange.format.rowHeight = 34;
}

